<script>
document.addEventListener('DOMContentLoaded', function() {
  // Animated Counter for Impact Stats
  const counters = document.querySelectorAll('[data-count]');
  const speed = 200;
  
  const animateCounter = (counter) => {
    const target = +counter.getAttribute('data-count');
    const increment = target / speed;
    
    const updateCount = () => {
      const count = +counter.innerText;
      
      if (count < target) {
        counter.innerText = Math.ceil(count + increment);
        setTimeout(updateCount, 1);
      } else {
        counter.innerText = target + (counter.innerText.includes('+') ? '+' : (counter.innerText.includes('%') ? '%' : ''));
      }
    };
    
    updateCount();
  };
  
  // Intersection Observer for animation trigger
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        animateCounter(entry.target);
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.5 });
  
  counters.forEach(counter => {
    observer.observe(counter);
  });

  // Success Stories Slider
  const successTrack = document.querySelector('.success-track');
  const successCards = document.querySelectorAll('.success-card');
  
  if (successTrack && successCards.length > 0) {
    let currentSlide = 0;
    const totalSlides = successCards.length;
    
    // Auto-play functionality
    function startAutoPlay() {
      setInterval(() => {
        currentSlide = (currentSlide + 1) % totalSlides;
        updateSlider();
      }, 4000);
    }
    
    function updateSlider() {
      const slideWidth = 100 / 3; // Show 3 cards at a time
      const offset = currentSlide * slideWidth;
      successTrack.style.transform = `translateX(-${offset}%)`;
    }
    
    // Touch/Swipe support
    let startX = 0;
    let isDragging = false;
    
    successTrack.addEventListener('touchstart', (e) => {
      startX = e.touches[0].clientX;
      isDragging = true;
    });
    
    successTrack.addEventListener('touchend', (e) => {
      if (!isDragging) return;
      isDragging = false;
      
      const endX = e.changedTouches[0].clientX;
      const diff = startX - endX;
      
      if (Math.abs(diff) > 50) {
        if (diff > 0) {
          currentSlide = (currentSlide + 1) % totalSlides;
        } else {
          currentSlide = (currentSlide - 1 + totalSlides) % totalSlides;
        }
        updateSlider();
      }
    });
    
    // Start auto-play
    startAutoPlay();
  }

  // Recruiter Item Hover Effects
  const recruiterItems = document.querySelectorAll('.recruiter-item');
  recruiterItems.forEach(item => {
    item.addEventListener('mouseenter', function() {
      this.style.transform = 'scale(1.05) translateY(-5px)';
    });
    
    item.addEventListener('mouseleave', function() {
      this.style.transform = 'scale(1) translateY(0)';
    });
  });

  // Outcome Card Animations
  const outcomeCards = document.querySelectorAll('.outcome-card');
  outcomeCards.forEach((card, index) => {
    card.style.animationDelay = `${index * 0.1}s`;
    card.style.animation = 'fadeInUp 0.6s ease forwards';
  });

  // Impact Card Hover Effects
  const impactCards = document.querySelectorAll('.impact-card');
  impactCards.forEach(card => {
    card.addEventListener('mouseenter', function() {
      const icon = this.querySelector('.impact-icon');
      if (icon) {
        icon.style.transform = 'scale(1.2) rotate(10deg)';
      }
    });
    
    card.addEventListener('mouseleave', function() {
      const icon = this.querySelector('.impact-icon');
      if (icon) {
        icon.style.transform = 'scale(1) rotate(0deg)';
      }
    });
  });
});

