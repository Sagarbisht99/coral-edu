<script>
  document.addEventListener('DOMContentLoaded', function() {
    // Animated Counter
    const counters = document.querySelectorAll('[data-count]');
    const speed = 200;

    const animateCounter = (counter) => {
      const target = +counter.getAttribute('data-count');
      const increment = target / speed;

      const updateCount = () => {
        const count = +counter.innerText;

        if (count < target) {
          counter.innerText = Math.ceil(count + increment);
          setTimeout(updateCount, 1);
        } else {
          counter.innerText = target + (counter.innerText.includes('+') ? '+' : (counter.innerText.includes('%') ? '%' : ''));
        }
      };

      updateCount();
    };

    // Intersection Observer for animation trigger
    const observer = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          animateCounter(entry.target);
          observer.unobserve(entry.target);
        }
      });
    }, {
      threshold: 0.5
    });

    counters.forEach(counter => {
      observer.observe(counter);
    });

    // Placement Stats Slider Functionality
    const sliderTrack = document.querySelector('.placement-stats-slider .slider-track');
    const prevBtn = document.querySelector('.placement-stats-slider .prev-btn');
    const nextBtn = document.querySelector('.placement-stats-slider .next-btn');
    const dots = document.querySelectorAll('.placement-stats-slider .dot');
    const statItems = document.querySelectorAll('.placement-stats-slider .stat-item');

    if (sliderTrack && prevBtn && nextBtn && dots.length > 0) {
      let currentSlide = 0;
      const totalSlides = statItems.length;

      // Calculate how many slides to show based on screen size
      function getSlidesPerView() {
        if (window.innerWidth <= 768) return 1;
        if (window.innerWidth <= 992) return 2;
        return 4;
      }

      function updateSlider() {
        const slidesPerView = getSlidesPerView();
        const maxSlide = Math.max(0, totalSlides - slidesPerView);
        currentSlide = Math.min(currentSlide, maxSlide);

        const slideWidth = 100 / slidesPerView;
        const offset = currentSlide * slideWidth;

        sliderTrack.style.transform = `translateX(-${offset}%)`;

        // Update dots
        dots.forEach((dot, index) => {
          dot.classList.toggle('active', index === currentSlide);
        });

        // Update button states
        prevBtn.disabled = currentSlide === 0;
        nextBtn.disabled = currentSlide >= maxSlide;
      }

      function nextSlide() {
        const slidesPerView = getSlidesPerView();
        const maxSlide = Math.max(0, totalSlides - slidesPerView);
        if (currentSlide < maxSlide) {
          currentSlide++;
          updateSlider();
        }
      }

      function prevSlide() {
        if (currentSlide > 0) {
          currentSlide--;
          updateSlider();
        }
      }

      function goToSlide(slideIndex) {
        currentSlide = slideIndex;
        updateSlider();
      }

      // Event listeners
      nextBtn.addEventListener('click', nextSlide);
      prevBtn.addEventListener('click', prevSlide);

      dots.forEach((dot, index) => {
        dot.addEventListener('click', () => goToSlide(index));
      });

      // Touch/swipe support
      let startX = 0;
      let isDragging = false;

      sliderTrack.addEventListener('touchstart', (e) => {
        startX = e.touches[0].clientX;
        isDragging = true;
      });

      sliderTrack.addEventListener('touchmove', (e) => {
        if (!isDragging) return;
        e.preventDefault();
      });

      sliderTrack.addEventListener('touchend', (e) => {
        if (!isDragging) return;
        isDragging = false;

        const endX = e.changedTouches[0].clientX;
        const diff = startX - endX;

        if (Math.abs(diff) > 50) {
          if (diff > 0) {
            nextSlide();
          } else {
            prevSlide();
          }
        }
      });

      // Mouse drag support
      sliderTrack.addEventListener('mousedown', (e) => {
        startX = e.clientX;
        isDragging = true;
        sliderTrack.style.cursor = 'grabbing';
      });

      sliderTrack.addEventListener('mousemove', (e) => {
        if (!isDragging) return;
        e.preventDefault();
      });

      sliderTrack.addEventListener('mouseup', (e) => {
        if (!isDragging) return;
        isDragging = false;
        sliderTrack.style.cursor = 'grab';

        const endX = e.clientX;
        const diff = startX - endX;

        if (Math.abs(diff) > 50) {
          if (diff > 0) {
            nextSlide();
          } else {
            prevSlide();
          }
        }
      });

      sliderTrack.addEventListener('mouseleave', () => {
        isDragging = false;
        sliderTrack.style.cursor = 'grab';
      });

      // Handle window resize
      window.addEventListener('resize', () => {
        updateSlider();
      });

      // Auto-play (optional)
      let autoPlayInterval;

      function startAutoPlay() {
        autoPlayInterval = setInterval(() => {
          const slidesPerView = getSlidesPerView();
          const maxSlide = Math.max(0, totalSlides - slidesPerView);

          if (currentSlide >= maxSlide) {
            currentSlide = 0;
          } else {
            currentSlide++;
          }

          updateSlider();
        }, 5000);
      }

      function stopAutoPlay() {
        clearInterval(autoPlayInterval);
      }

      // Start auto-play
      startAutoPlay();

      // Pause on hover
      const sliderContainer = document.querySelector('.placement-stats-slider .slider-container');
      sliderContainer.addEventListener('mouseenter', stopAutoPlay);
      sliderContainer.addEventListener('mouseleave', startAutoPlay);

      // Initialize slider
      updateSlider();
    }
  });
</script>